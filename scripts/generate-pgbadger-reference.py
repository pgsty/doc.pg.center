#!/usr/bin/env python3
"""Generate English pgBadger reference pages without overwriting reviewed translations."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


PROJECT = Path(__file__).resolve().parent.parent
SOURCE = PROJECT / "sources" / "pgbadger" / "upstream"
CONTENT = PROJECT / "content" / "docs" / "pgbadger"
COMMIT = "a1ad95a035a0c2d246fe632eb1c361d4bde0ddae"
SOURCE_URL = f"https://github.com/darold/pgbadger/tree/{COMMIT}"
CHECK_ONLY = False


def write_reference(path: Path, text: str) -> None:
    if CHECK_ONLY:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            raise RuntimeError(f"English reference is stale: {path.relative_to(PROJECT)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def normalize_source_markdown(text: str) -> str:
    return (
        text.replace(r"\_", "_")
        .replace(r"\[", "[")
        .replace(r"\]", "]")
        .replace(r"\--", "--")
        .strip()
    )


def fence_indented_blocks(text: str) -> str:
    """Turn POD-generated four-space blocks into explicit text fences."""
    lines = text.splitlines()
    output: list[str] = []
    block: list[str] = []

    def flush() -> None:
        nonlocal block
        while block and not block[-1]:
            block.pop()
        if block:
            output.extend(["```text", *block, "```"])
        block = []

    for index, line in enumerate(lines):
        next_indented = index + 1 < len(lines) and lines[index + 1].startswith("    ")
        if line.startswith("    "):
            block.append(line[4:])
        elif block and not line and next_indented:
            block.append("")
        else:
            flush()
            output.append(line)
    flush()
    return "\n".join(output).strip()


def read_readme_section(name: str) -> str:
    readme = (SOURCE / "README.md").read_text(encoding="utf-8")
    match = re.search(
        rf"^### {re.escape(name)}\s*$\n(.*?)(?=^### [A-Z][A-Z ]+\s*$|\Z)",
        readme,
        flags=re.MULTILINE | re.DOTALL,
    )
    if not match:
        raise RuntimeError(f"README section not found: {name}")
    body = fence_indented_blocks(normalize_source_markdown(match.group(1)))
    # Reviewed upstream errata: a misplaced continuation, a year typo, and
    # escaped code delimiters. Keep the pinned source snapshot unchanged.
    if name == "SYNOPSIS":
        body = body.replace("useful to hide\n", "useful to hide\n                         confidential data.\n", 1)
        body = body.replace("do not generate autovacuum report.\n                         confidential data.", "do not generate autovacuum report.", 1)
        body = body.replace("--month-report 2919-05", "--month-report 2019-05")
        body = body.replace(r"\`jsonlog\`", "`jsonlog`")
        body = body.replace(
            "This will help avoid having COPY statements, as generated by pg_dump, on top of",
            "This expression excludes each entire matching hour, including time outside the half-hour dump. "
            "Narrow the minute pattern if only the dump interval should be excluded.\n\n"
            "This will help avoid having COPY statements, as generated by pg_dump, on top of",
        )
        body = body.replace("--ssh-user username      connection login name. Defaults to running user.\n```", "--ssh-user username      connection login name. Defaults to running user.\n```\n\n`--ssh-sudo` prefixes remote file-listing and log-reading commands with `sudo`. The remote SSH user must be able to run those commands through `sudo` without an interactive prompt.")
    return body


def write_command_reference() -> None:
    body = read_readme_section("SYNOPSIS")
    keywords = reference_keywords(body)
    common = f"""
## Usage and options {{#usage-and-options}}

{body}
""".strip()

    english = f"""---
title: "Command-Line Reference"
linkTitle: "Command Line"
weight: 30
description: "Complete pgBadger command syntax, options, remote input, return codes, and examples"
search_keywords: {keywords}
search_boost: 8
icon: fa-solid fa-terminal
module: [PGBADGER]
categories: [Reference]
aliases: [/pgbadger/command-line/]
upstream_link: "{SOURCE_URL}/README.md"
upstream_name: "pgBadger README.md"
---

{common}
"""

    write_reference(CONTENT / "command-line.md", english)


def changelog_entries() -> dict[int, list[tuple[str, str, str]]]:
    changelog = (SOURCE / "ChangeLog").read_text(encoding="utf-8")
    starts = list(
        re.finditer(
            r"^(\d{4}-\d{2}-\d{2}) - v(\d+\.\d+)\s*$",
            changelog,
            flags=re.MULTILINE,
        )
    )
    result: dict[int, list[tuple[str, str, str]]] = {major: [] for major in range(9, 14)}
    for index, match in enumerate(starts):
        version = match.group(2)
        major = int(version.split(".", 1)[0])
        if major not in result:
            continue
        end = starts[index + 1].start() if index + 1 < len(starts) else len(changelog)
        body = normalize_source_markdown(changelog[match.end() : end])
        # These PostgreSQL settings have always used these spellings; the
        # singular/incorrect forms in the ChangeLog are documentation typos.
        body = re.sub(r"\blog_connection\b", "log_connections", body)
        body = re.sub(r"\blog_disconnection\b|\blog disconnection\b", "log_disconnections", body)
        body = body.replace("log_in_duration_statement", "log_min_duration_statement")
        if version == "11.5":
            # The original formula omitted grouping and an ending quote;
            # the implementation subtracts before dividing by session count.
            body = body.replace('"total sessions time - total queries time / number of sessions', '"(total sessions time - total queries time) / number of sessions"')
        if version == "10.0":
            body = body.replace("--exlucde-time", "--exclude-time")
        if version == "11.0":
            body = body.replace("`$prefix_vars{'t_time'} to", "`$prefix_vars{'t_time'}` to")
        result[major].append((version, match.group(1), body))
    return result


def reference_keywords(body: str) -> str:
    """Expose technical terms hidden in code blocks to the local search index."""
    pattern = (
        r"(?<![\w-])--[A-Za-z][A-Za-z_-]*|(?<!\w)log_[a-z_]+|lc_messages|"
        r"\b(?:csvlog|jsonlog|stderr|syslog|logplex|redshift|zstdcat)\b|"
        r"Text::CSV_XS|JSON::XS"
    )
    keywords = set(re.findall(pattern, body))
    # Lunr tokenizes a query such as --ssh-sudo into ssh and sudo, while
    # keyword arrays keep each element whole. Include those query forms too.
    for value in tuple(keywords):
        if value.startswith("--"):
            bare = value[2:]
            keywords.add(bare)
            keywords.update(bare.split("-"))
    return "[" + ", ".join(sorted(keywords)) + "]"


def write_release_pages() -> None:
    release_dir = CONTENT / "releases"
    entries = changelog_entries()
    weights = {13: 10, 12: 20, 11: 30, 10: 40, 9: 50}

    for major in range(13, 8, -1):
        sections: list[str] = []
        for version, date, body in entries[major]:
            sections.append(f"## v{version} · {date} {{#v{version.replace('.', '-')}}}\n\n{body}")
        release_text = "\n\n".join(sections)
        common = release_text
        keywords = reference_keywords(common)

        english = f"""---
title: "pgBadger {major}.x Release Notes"
linkTitle: "{major}.x"
weight: {weights[major]}
description: "Complete upstream release notes for the pgBadger {major}.x series"
search_keywords: {keywords}
icon: fa-solid fa-code-branch
module: [PGBADGER]
categories: [Reference]
aliases: [/pgbadger/releases/{major}/]
upstream_link: "{SOURCE_URL}/ChangeLog"
upstream_name: "pgBadger ChangeLog"
---

{common}
"""

        write_reference(release_dir / f"{major}.md", english)


def main() -> None:
    global CHECK_ONLY
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify English references without writing files")
    CHECK_ONLY = parser.parse_args().check
    write_command_reference()
    write_release_pages()
    print("Verified" if CHECK_ONLY else "Generated", "English pgBadger references; reviewed translations are preserved.")


if __name__ == "__main__":
    main()
