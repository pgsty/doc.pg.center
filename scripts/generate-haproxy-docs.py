def remove_legacy_directories() -> None:
    """Remove the generated nested layout after verifying that it contains no foreign files."""
    for manual in MANUAL_PAGES:
        legacy_dir = CONTENT / manual
        if not legacy_dir.exists():
            continue
        if not legacy_dir.is_dir():
            raise RuntimeError(f"expected legacy HAProxy path to be a directory: {legacy_dir}")
        foreign = [
            path
            for path in legacy_dir.rglob("*")
            if path.is_file()
            and (path.suffix != ".md" or GENERATED_MARKER not in path.read_text(encoding="utf-8"))
        ]
        if foreign:
            raise RuntimeError(f"refusing to remove non-generated files: {foreign}")
        shutil.rmtree(legacy_dir)


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as temporary:
        temporary.write(text)
        temporary_path = Path(temporary.name)
    temporary_path.replace(path)


def verify_coverage(manual: str, pages: tuple[Page, ...], sections: dict[str, Section]) -> None:
    covered: list[str] = []
    for page in pages:
        chapter = page.section_numbers[0]
        covered.extend(
            number
            for number in sections
            if number == chapter or number.startswith(f"{chapter}.")
        )
    if len(covered) != len(set(covered)):
        raise RuntimeError(f"overlapping {manual} section mappings")
    missing = set(sections).difference(covered)
    unexpected = set(covered).difference(sections)
    if missing or unexpected:
        raise RuntimeError(
            f"{manual} coverage mismatch; missing={sorted(missing)}, unexpected={sorted(unexpected)}"
        )


def main() -> None:
    intro_lead, intro_sections = parse_manual("intro.txt")
    configuration_lead, configuration_sections = parse_manual("configuration.txt")
    management_lead, management_sections = parse_manual("management.txt")

    intro_expected = {number for page in INTRO_PAGES for number in page.section_numbers}
    if intro_expected != set(intro_sections):
        raise RuntimeError(
            f"intro coverage mismatch; missing={sorted(set(intro_sections) - intro_expected)}, "
            f"unexpected={sorted(intro_expected - set(intro_sections))}"
        )
    verify_coverage("configuration", CONFIGURATION_CHAPTERS, configuration_sections)
    verify_coverage("management", MANAGEMENT_CHAPTERS, management_sections)

    remove_legacy_directories()
    atomic_write(CONTENT / "_index.md", render_root_index())
    for manual in MANUAL_PAGES:
        atomic_write(CONTENT / f"_div_{manual}.md", render_divider(manual))

    for index, page in enumerate(INTRO_PAGES):
        introduction = intro_lead if index == 0 else ""
        atomic_write(
            CONTENT / page.filename,
            render_intro_page(page, intro_sections, introduction),
        )

    manual_inputs = (
        ("configuration", CONFIGURATION_CHAPTERS, configuration_sections, configuration_lead),
        ("management", MANAGEMENT_CHAPTERS, management_sections, management_lead),
    )
    for manual, pages, sections, introduction in manual_inputs:
        for index, page in enumerate(pages):
            atomic_write(
                CONTENT / page.filename,
                render_chapter_page(
                    page,
                    manual,
                    sections,
                    introduction if index == 0 else "",
                ),
            )

    total = 1 + len(DIVIDER_WEIGHTS) + sum(len(pages) for pages in MANUAL_PAGES.values())
    print(
        f"Generated {total} flat HAProxy Markdown files from {UPSTREAM_TAG}: "
        f"3 sidebar dividers, 9 intro topics, {len(CONFIGURATION_CHAPTERS)} configuration chapters, "
        f"and {len(MANAGEMENT_CHAPTERS)} management chapters."
    )


if __name__ == "__main__":
    main()
