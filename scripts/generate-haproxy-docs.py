def section_label(section_numbers: tuple[str, ...]) -> str:
    if len(section_numbers) == 1:
        return f"chapter {section_numbers[0]}"
    if section_numbers == ("1", "5"):
        return "chapters 1 and 5"
    return f"sections {section_numbers[0]}–{section_numbers[-1]}"


def page_front_matter(page: Page, manual: str) -> str:
    """Front matter, including the upstream attribution the OINK page annotation
    renders at the page end. `upstream_source: haproxy` cascades from the root;
    the per-page facts are which manual and which of its chapters this page
    preserves."""
    return f'''---
title: "{page.title}"
linkTitle: "{page.link_title}"
weight: {page.weight}
description: "{page.description}"
icon: {page.icon}
module: [HAPROXY]
categories: [{page.category}]
{aliases_yaml(page_aliases(manual, page))}upstream_link: "{DOCS_BASE}/{manual}.html"
upstream_name: "HAProxy 3.4 {MANUAL_NAMES[manual]}"
upstream_ref: "{UPSTREAM_TAG}, {section_label(page.section_numbers)}"
---'''


def render_intro_page(page: Page, sections: dict[str, Section], introduction: str = "") -> str:
    selected = [sections[number] for number in page.section_numbers]
    if page.merge_lead_section:
        lead = normalize_body(selected[0].body, "intro", selected[0].number)
        remaining = selected[1:]
        if remaining:
            base_depth = min(len(section.number.split(".")) for section in remaining)
            remainder = "\n\n".join(render_section(section, base_depth, "intro") for section in remaining)
            rendered = "\n\n".join(part for part in (lead, remainder) if part)
        else:
            rendered = lead
    else:
        base_depth = min(len(section.number.split(".")) for section in selected)
        rendered = "\n\n".join(render_section(section, base_depth, "intro") for section in selected)

    if introduction:
        intro = normalize_body(introduction, "intro")
        intro = re.sub(
            r"The summary below is meant to help you search sections by name and navigate\s+through the document\.",
            "The guide is presented as a flat sequence of topic pages in the HAProxy sidebar.",
            intro,
        )
        rendered = "\n\n".join((intro, rendered))

    extras = ""
    if page.filename == "resources.md":
        extras = f'''

## Complete local manual set {{#complete-local-manual-set}}

- [Starter Guide]({MANUAL_PATHS['intro']})
- [Configuration Manual]({MANUAL_PATHS['configuration']})
- [Management Guide]({MANUAL_PATHS['management']})

## Edition provenance {{#edition-provenance}}

- **Edition:** HAProxy {UPSTREAM_VERSION}, tag `{UPSTREAM_TAG}`
- **Source commit:** [`{UPSTREAM_COMMIT[:12]}`](https://git.haproxy.org/?p=haproxy-3.4.git;a=commit;h={UPSTREAM_COMMIT})
- **Rendered upstream set:** [docs.haproxy.org/3.4/]({DOCS_BASE}/)
- **Local license copies:** [HAProxy license notice](/third_party/haproxy/LICENSE) and [GPLv2](/third_party/haproxy/GPL-2.0)
'''.rstrip()

    return (
        f"{page_front_matter(page, 'intro')}\n\n"
        "<!-- Generated by scripts/generate-haproxy-docs.py from pinned upstream text. -->\n\n"
        f"{rendered}{extras}\n"
    )


def chapter_sections(chapter: str, sections: dict[str, Section]) -> list[Section]:
    return [
        section
        for number, section in sections.items()
        if number == chapter or number.startswith(f"{chapter}.")
    ]


def render_chapter_page(
    page: Page,
    manual: str,
    sections: dict[str, Section],
    introduction: str = "",
) -> str:
    chapter = page.section_numbers[0]
    selected = chapter_sections(chapter, sections)
    lead = normalize_body(selected[0].body, manual, selected[0].number)
    descendants = selected[1:]
    remainder = "\n\n".join(render_section(section, 2, manual) for section in descendants)
    intro = normalize_body(introduction, manual) if introduction else ""
    if manual == "configuration" and intro:
        intro = re.sub(
            r"The summary below is meant to help you find sections by\s+name and navigate through the document\.",
            "The numbered chapters are ordered in the flat HAProxy sidebar for direct navigation.",
            intro,
        )
    rendered = "\n\n".join(part for part in (intro, lead, remainder) if part)
    return (
        f"{page_front_matter(page, manual)}\n\n"
        "<!-- Generated by scripts/generate-haproxy-docs.py from pinned upstream text. -->\n\n"
        f"{rendered}\n"
    )


